#!/usr/bin/env node
// Offline-only tests for the fresh, one-shot v3.8 authorization gate.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PHASE2_V38_AUTHORIZATION_ID, draftV38SpecPath, authorizedV38SpecPath,
  v38AuthorizationRecordPath, validatePhase2V38Authorization } from './phase2-v38-execution-authorization.mjs';
const here=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(here,'../..');
const record=JSON.parse(fs.readFileSync(v38AuthorizationRecordPath,'utf8'));
const previous=JSON.parse(fs.readFileSync(path.join(here,'phase2-case01-v3.8-execution-authorization-20261012.json'),'utf8'));
const previousConsumption=JSON.parse(fs.readFileSync(path.resolve(repo,previous.consumption_record_path),'utf8'));
const previousSecond=JSON.parse(fs.readFileSync(path.join(here,'phase2-case01-v3.8-execution-authorization-20261012-02.json'),'utf8'));
const previousSecondConsumption=JSON.parse(fs.readFileSync(path.resolve(repo,previousSecond.consumption_record_path),'utf8'));
const previousThird=JSON.parse(fs.readFileSync(path.join(here,'phase2-case01-v3.8-execution-authorization-20261012-03.json'),'utf8'));
const previousThirdConsumption=JSON.parse(fs.readFileSync(path.resolve(repo,previousThird.consumption_record_path),'utf8'));
const previousFourth=JSON.parse(fs.readFileSync(path.join(here,'phase2-case01-v3.8-execution-authorization-20261012-04.json'),'utf8'));
const previousFourthConsumption=JSON.parse(fs.readFileSync(path.resolve(repo,previousFourth.consumption_record_path),'utf8'));
const previousFifth=JSON.parse(fs.readFileSync(path.join(here,'phase2-case01-v3.8-execution-authorization-20261012-05.json'),'utf8'));
const previousFifthConsumption=JSON.parse(fs.readFileSync(path.resolve(repo,previousFifth.consumption_record_path),'utf8'));
const previousSixth=JSON.parse(fs.readFileSync(path.join(here,'phase2-case01-v3.8-execution-authorization-20261012-06.json'),'utf8'));
const previousSixthConsumption=JSON.parse(fs.readFileSync(path.resolve(repo,previousSixth.consumption_record_path),'utf8'));
const bytes=fs.readFileSync(authorizedV38SpecPath);
const output=path.resolve(repo,record.output_path);
assert.equal(record.decision_id,PHASE2_V38_AUTHORIZATION_ID);
assert.equal(record.consumption_status,'fresh-not-yet-consumed');
const currentConsumptionPath=path.resolve(repo,record.consumption_record_path);
const currentIsConsumed=fs.existsSync(currentConsumptionPath);
const currentConsumption=currentIsConsumed ? JSON.parse(fs.readFileSync(currentConsumptionPath,'utf8')) : null;
if (currentIsConsumed) {
  assert.equal(currentConsumption.authorization_id,record.decision_id);
  assert.equal(currentConsumption.case_id,'CASE-01');
  assert.equal(path.resolve(currentConsumption.output_path),output);
  assert.equal(currentConsumption.status,'consumed-before-workspace-or-model-invocation');
}
assert.equal(previous.decision_id,'phase2-case01-v3.8-one-shot-20261012-01');
assert.equal(previous.consumption_status,'consumed-before-workspace-or-model-invocation');
assert.equal(previousConsumption.authorization_id,previous.decision_id);
assert.equal(previousConsumption.run_id,'849fd89d-1708-45fa-ac57-716e57039e34');
assert.equal(previousConsumption.status,previous.consumption_status);
assert.equal(previousSecond.decision_id,'phase2-case01-v3.8-one-shot-20261012-02');
assert.equal(previousSecond.consumption_status,'consumed-before-workspace-or-model-invocation');
assert.equal(previousSecondConsumption.authorization_id,previousSecond.decision_id);
assert.equal(previousSecondConsumption.run_id,'fb5d39e0-0724-474a-80ed-79cacd844dd1');
assert.equal(previousSecondConsumption.status,previousSecond.consumption_status);
assert.equal(previousThird.decision_id,'phase2-case01-v3.8-one-shot-20261012-03');
assert.equal(previousThird.consumption_status,'fresh-not-yet-consumed','consumption is recorded durably in its separate record without mutating the authorization decision');
assert.equal(previousThirdConsumption.authorization_id,previousThird.decision_id);
assert.equal(previousThirdConsumption.run_id,'982ab973-a409-42b0-97da-9cd4a8c88e82');
assert.equal(previousThirdConsumption.status,'consumed-before-workspace-or-model-invocation');
assert.equal(previousFourth.decision_id,'phase2-case01-v3.8-one-shot-20261012-04');
assert.equal(previousFourth.consumption_status,'fresh-not-yet-consumed','durable consumption is recorded separately from the immutable authorization decision');
assert.equal(previousFourthConsumption.authorization_id,previousFourth.decision_id);
assert.equal(previousFourthConsumption.run_id,'28262ff7-5cfa-42e0-8576-53257913381c');
assert.equal(previousFourthConsumption.status,'consumed-before-workspace-or-model-invocation');
assert.equal(previousFifth.decision_id,'phase2-case01-v3.8-one-shot-20261012-05');
assert.equal(previousFifth.consumption_status,'fresh-not-yet-consumed','durable consumption is recorded separately from the immutable authorization decision');
assert.equal(previousFifthConsumption.authorization_id,previousFifth.decision_id);
assert.equal(previousFifthConsumption.run_id,'17b7df3e-ced1-4883-9dd9-377c8a8860a5');
assert.equal(previousFifthConsumption.status,'consumed-before-workspace-or-model-invocation');
assert.equal(previousSixth.decision_id,'phase2-case01-v3.8-one-shot-20261012-06');
assert.equal(previousSixth.consumption_status,'fresh-not-yet-consumed','durable consumption is recorded separately from the immutable authorization decision');
assert.equal(previousSixthConsumption.authorization_id,previousSixth.decision_id);
assert.equal(previousSixthConsumption.run_id,'20112dac-17a5-4d14-a392-e268e0161923');
assert.equal(previousSixthConsumption.status,'consumed-before-workspace-or-model-invocation');
assert.equal(JSON.parse(fs.readFileSync(draftV38SpecPath,'utf8')).execution_gate.status,'blocked');
assert.equal(JSON.parse(bytes).execution_gate.status,'authorized');
const validated=validatePhase2V38Authorization({specPath:authorizedV38SpecPath,specBytes:bytes,caseId:'CASE-01',outputPath:output,runId:currentConsumption?.run_id,requireConsumed:currentIsConsumed});
assert.equal(validated.record.decision_id,PHASE2_V38_AUTHORIZATION_ID);
assert.throws(()=>validatePhase2V38Authorization({specPath:authorizedV38SpecPath,specBytes:bytes,caseId:'CASE-02',outputPath:output}),/scoped to CASE-01/);
assert.throws(()=>validatePhase2V38Authorization({specPath:authorizedV38SpecPath,specBytes:bytes,caseId:'CASE-01',outputPath:path.join(repo,'wrong-output.json')}),/output path differs/);
assert.throws(()=>validatePhase2V38Authorization({specPath:draftV38SpecPath,specBytes:fs.readFileSync(draftV38SpecPath),caseId:'CASE-01',outputPath:output}),/only the one-case authorized v3.8 execution spec/);
console.log('PASS: v3.8 one-shot authorization reconciles to exact source/execution hashes, unique output path, and active pilot consumption record');
console.log('PASS: prior v3.8 one-shot remains durably consumed and cannot be reused');
console.log('PASS: the second v3.8 one-shot remains durably consumed after a pre-invocation output-path rejection');
console.log('PASS: the third v3.8 one-shot remains durably consumed after the plugin lineage pilot failed independent acceptance checks');
console.log('PASS: the fourth v3.8 one-shot remains durably consumed after the artifact-shape pilot failed typed-content validation');
console.log('PASS: the fifth v3.8 one-shot remains durably consumed after the model failed to produce a compliant CASE-01 workflow proposal');
console.log('PASS: the sixth v3.8 one-shot remains durably consumed after the plugin reached an active task but did not execute it or produce typed artifacts');
console.log('PASS: only CASE-01 is authorized; draft remains blocked; output path, spec path, and authorization identity are enforced');
console.log(`PASS: static authorization tests execute no model or benchmark scenario; current one-shot consumed=${currentIsConsumed}`);
