#!/usr/bin/env node
// Offline-only static regression for the eighth remediation candidate.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const read=name=>fs.readFileSync(path.join(here,name),'utf8');
const v37=JSON.parse(read('scenario-execution-spec-v3.7-draft.json'));
const v38Bytes=read('scenario-execution-spec-v3.8-draft.json');
const v38=JSON.parse(v38Bytes);
assert.deepEqual(v38.cases,v37.cases,'all ten frozen prompts and per-case grants must remain byte-identical');
assert.equal(v38.cases.length,10);
assert.equal(v38.frozen_baseline.source_spec_sha256,v37.frozen_baseline.source_spec_sha256);
assert.equal(v38.status,'draft-not-authorized');
assert.equal(v38.execution_gate.status,'blocked');
assert.deepEqual(v38.execution_gate.authorized_case_ids,[]);
assert.equal(v38.execution_gate.authorization_record,null);
assert.equal(v38.paired_conditions.identical_prompt_bytes,true);
assert.equal(v38.paired_conditions.fresh_workspace_and_sqlite_per_condition,true);
assert.equal(v38.paired_conditions.no_external_network_or_provider_credentials,true);
assert.equal(v38.paired_conditions.no_live_runtime_or_shared_service,true);
assert.deepEqual(v38.model,v37.model,'no runtime limits may change in a context-only revision');
assert.ok(v38.system_context.length < v37.system_context.length * 0.87,'shared system context should be at least 13% shorter');
for (const token of ['custom_role_create','custom_workflow_create','custom_workflow_preview','custom_workflow_approve','custom_workflow_run_create','workflow_approve','workflow_dispatch','workflow_prepare_tasks','workflow_next_task','workflow_complete_task','workflow_complete_synthesis','workflow_recovery_verify','case01-requirements','product.requirements','role version 1','no dependencies','/case/workspace','workspace_artifacts','actual final-byte SHA-256','acceptance_criteria','non_goals','expected values','exact bytes','private DB','identical across paired conditions']) assert.ok(v38.system_context.includes(token),`missing required instruction: ${token}`);
assert.equal((v38.system_context.match(/validate required fields/g) ?? []).length,2,'both JSON artifacts must retain explicit required-field validation');
assert.match(v38.system_context,/Do not write files until workflow_next_task returns an active task/);
assert.match(v38.system_context,/write_file config\.json with exact bytes \{"service":"demo","port":43127\} \(no newline\); do not read\/list first/);
assert.match(v38.system_context,/write result\.json exact bytes \{"validated":true,"service":"demo"\} \(no newline\)/);
assert.match(v38.system_context,/Control uses basic tools only/);
assert.match(v38.system_context,/System and user prompt bytes must be identical across paired conditions/);
assert.match(v38.system_context,/If passed=true/);
assert.match(v38.system_context,/terminal-success/);
assert.match(v38.system_context,/cannot claim plugin evidence/);
assert.match(v38.system_context,/workspace \/case\/workspace/);
assert.doesNotMatch(v38.system_context,/Use basic tools for the requested files/i,
  'the plugin condition must not be instructed to bypass its workflow with basic tools');
const case01=v38.cases.find(item=>item.case_id==='CASE-01');
assert.ok(case01,'CASE-01 must exist');
assert.equal(case01.execution_contract.mode,'artifact-lineage');
assert.deepEqual(case01.execution_contract.required_workspace_files,['config.json','result.json']);
assert.equal(case01.execution_policy.workflow_execution_allowed,true);
assert.equal(case01.execution_policy.workspace_mutation_allowed,true);
assert.match(case01.execution_contract.artifact_lineage_rule,/actual workspace file bytes/);
assert.match(case01.execution_contract.artifact_lineage_rule,/completed task/);
assert.match(case01.execution_contract.artifact_lineage_rule,/CTO decision must reference the task artifact ID/);
console.log(`PASS: v3.8 draft ${createHash('sha256').update(v38Bytes).digest('hex')} preserves all ten frozen prompts, per-case grants, and model limits`);
console.log(`PASS: shared system context reduced by ${v37.system_context.length-v38.system_context.length} characters (${Math.round((1-v38.system_context.length/v37.system_context.length)*100)}%) while retaining workflow, validation, lineage, parity, and independent-verification requirements`);
console.log('PASS: blocked execution gate remains closed; static-only test runs no scenario, plugin process, or model inference');
