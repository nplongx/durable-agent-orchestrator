import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { verifyExecutionEvidence } from '../src/runtime/execution-verifier.js';

const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const inputCommit = 'a'.repeat(40);
const outputCommit = 'b'.repeat(40);
const result = {
  schema_version: 1,
  job_id: 'job_build143', task_id: 'task_build143', lease_id: 'lease_build143', attempt: 1, owner_epoch: 1,
  status: 'SUCCEEDED', input_commit: inputCommit, output_commit: outputCommit, exit_code: 0,
  provider_run_id: '143', provider_run_attempt: 1, evidence_artifact: 'p3-worker-143',
  evidence_refs: ['task-payload.json', 'execution.json', 'stdout.txt', 'stderr.txt', 'git-status.txt'],
  started_at: '2026-10-18T00:00:00.000Z', finished_at: '2026-10-18T00:00:01.000Z', error: null,
};
const payload = {
  schema_version: 1, job_id: result.job_id, task_id: result.task_id, lease_id: result.lease_id,
  attempt: result.attempt, owner_epoch: result.owner_epoch,
  required_evidence: [...result.evidence_refs],
};
const stdout = Buffer.from('task created a commit\n');
const stderr = Buffer.alloc(0);
const gitStatus = Buffer.from(' M tracked-file.txt\n');
const execution = {
  task_id: result.task_id, exit_code: 0, timed_out: false, output_commit: outputCommit,
  stdout_bytes: stdout.length, stderr_bytes: stderr.length, git_status_bytes: gitStatus.length,
  stdout_sha256: sha256(stdout), stderr_sha256: sha256(stderr), git_status_sha256: sha256(gitStatus),
};
const evidence = {
  'task-payload.json': payload,
  'execution.json': execution,
  'stdout.txt': stdout.toString('utf8'),
  'stderr.txt': stderr.toString('utf8'),
  'git-status.txt': gitStatus.toString('utf8'),
};
const evidenceBytes = {
  'result.json': Buffer.from(JSON.stringify(result)),
  'task-payload.json': Buffer.from(JSON.stringify(payload)),
  'execution.json': Buffer.from(JSON.stringify(execution)),
  'stdout.txt': stdout,
  'stderr.txt': stderr,
  'git-status.txt': gitStatus,
};
const verify = (nextResult, nextExecution, nextBytes = {}) => verifyExecutionEvidence({
  result: nextResult,
  evidence: { ...evidence, 'execution.json': nextExecution },
  evidenceBytes: {
    ...evidenceBytes,
    ...nextBytes,
    'result.json': nextBytes['result.json'] || Buffer.from(JSON.stringify(nextResult)),
    'execution.json': nextBytes['execution.json'] || Buffer.from(JSON.stringify(nextExecution)),
  },
  requireRawEvidenceBytes: true,
  trustedInputCommit: inputCommit,
});

const legitimateDistinctOutput = verify(result, execution);
assert.equal(legitimateDistinctOutput.valid, true,
  `post-execution output commit may differ from trusted input commit: ${legitimateDistinctOutput.errors.join('; ')}`);
assert.equal(legitimateDistinctOutput.output_commit_provenance,
  'worker_reported_and_execution_json_bound_not_independently_attested');

const resultOnlySubstitution = { ...result, output_commit: 'c'.repeat(40) };
const mismatch = verify(resultOnlySubstitution, execution);
assert.equal(mismatch.valid, false, 'result-only output commit substitution must fail');
assert.match(mismatch.errors.join('; '), /execution output_commit mismatch/);

// This is intentionally accepted as internally consistent, but explicitly not
// independently attested: both records are generated by the same worker.
const coordinatedClaim = 'd'.repeat(40);
const coordinatedResult = { ...result, output_commit: coordinatedClaim };
const coordinatedExecution = { ...execution, output_commit: coordinatedClaim };
const coordinated = verify(coordinatedResult, coordinatedExecution);
assert.equal(coordinated.valid, true, `coherent worker claim should pass consistency checks: ${coordinated.errors.join('; ')}`);
assert.equal(coordinated.output_commit_provenance,
  'worker_reported_and_execution_json_bound_not_independently_attested');

const inputAnchorSubstitution = { ...result, input_commit: 'e'.repeat(40) };
const badAnchor = verify(inputAnchorSubstitution, execution);
assert.equal(badAnchor.valid, false, 'artifact cannot replace the durable input commit anchor');
assert.match(badAnchor.errors.join('; '), /result input_commit does not match trusted input commit anchor/);

console.log('BUILD143 DISTINCT OUTPUT-COMMIT CONTRACT PASS');
